import { NextRequest, NextResponse } from "next/server";
import { ExportDiscoveryPackageSchema } from "@/lib/validations/structured-discovery";

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { projectId, format, includeUserFlows, includeEstimates, includeQuestionnaire } =
      ExportDiscoveryPackageSchema.parse(body);

    const timestamp = new Date().toISOString();

    if (format === "MARKDOWN") {
      const markdownDoc = `# SpecForge Discovery Package

**Project**: Fintech Mobile MVP (Sandbox)  
**Export Date**: ${timestamp}  
**Scope Health Score**: 92/100 (Grade A)  

---

## 1. Executive Summary & Goals
- **Business Goal**: Launch a modern mobile-first digital banking MVP.
- **Target Users**: Smartphone-first retail consumers and mobile freelancers.
- **Core Problem**: Traditional branch banking is slow and lacks automated budgeting tools.
- **Budget Range**: $15,000 - $35,000 | **Target Deadline**: 2027-02-15

---

## 2. MoSCoW Requirement Prioritization

### [MUST HAVE] Core Deliverables
1. **Phone OTP Login** (Business Value: 5/5, Effort: 2/5)
   - *Given* a user enters valid phone, *When* OTP arrives, *Then* session authenticates in < 2s.
2. **Biometric FaceID Authentication** (Business Value: 5/5, Effort: 3/5)
   - Fast login with keychain storage.
3. **Instant P2P Wallet Transfers** (Business Value: 5/5, Effort: 4/5)
   - Real-time balance ledger update.

### [SHOULD HAVE]
1. **Push Notifications** (Business Value: 4/5, Effort: 2/5)

### [COULD HAVE]
1. **Dark Mode Theme** (Business Value: 2/5, Effort: 1/5)

### [WON'T HAVE (Out of Scope for MVP)]
1. **Cryptocurrency Staking & Trading**

---

## 3. User Personas & Journey Flows
- **Persona 1**: Mobile Freelancer (Remote Contractor)
  - *Journey*: Wallet P2P Transfer (4 steps: WalletHome -> RecipientSelect -> BiometricAuth -> TransferReceipt)
  - *Edge Cases*: Insufficient balance, network timeout.

---

## 4. Assumptions & Commercial Boundaries
- **Assumption 1**: Client will provide verified Stripe / JazzCash API credentials 10 days prior to sprint start.
- **Exclusion 1**: Native watchOS and iPad tablet support are out of scope for MVP.

*Generated by SpecForge Discovery OS.*
`;

      return new NextResponse(markdownDoc, {
        status: 200,
        headers: {
          "Content-Type": "text/markdown; charset=utf-8",
          "Content-Disposition": `attachment; filename="Discovery-Package-${projectId}.md"`
        }
      });
    }

    if (format === "JSON") {
      const jsonPackage = {
        project: "Fintech Mobile MVP",
        version: "2.0",
        exportDate: timestamp,
        healthScore: { score: 92, grade: "A" },
        questionnaire: {
          businessGoal: "Launch a modern mobile-first digital banking MVP.",
          targetUsers: "Smartphone-first retail consumers."
        },
        requirementsCount: 8,
        personasCount: 2,
        flowsCount: 1
      };

      return NextResponse.json({
        success: true,
        data: jsonPackage
      });
    }

    // Default: Return success with downloadable asset metadata
    return NextResponse.json({
      success: true,
      data: {
        format,
        fileName: `Discovery-Package-${projectId}.${format.toLowerCase()}`,
        downloadUrl: `/downloads/discovery-${projectId}.${format.toLowerCase()}`,
        generatedAt: timestamp
      }
    });
  } catch (error: any) {
    return NextResponse.json(
      { success: false, error: { code: "EXPORT_FAILED", message: error.message } },
      { status: 400 }
    );
  }
}

